/**
 * Optional OpenAI augmentation for remediation text.
 *
 * Zak Security does NOT require an API key. Without OPENAI_API_KEY the
 * rule-based templates in ./templates.ts are used verbatim and the UI labels
 * the result as template-generated.
 *
 * With a key present, only the prose (why it matters / recommended fix) is
 * passed through the model. Code snippets always come from the templates so
 * the model can never invent a config value.
 */

import { getTemplateForCategory, type RemediationTemplate } from "./templates";

export type RemediationSource = "TEMPLATES" | "AI_ASSISTED";

export interface RemediationOutput {
  template: RemediationTemplate;
  source: RemediationSource;
  whyItMatters: string;
  recommendedFix: string;
  note?: string;
}

const MODEL = "gpt-4o-mini";

export function isOpenAiConfigured(): boolean {
  return Boolean(process.env.OPENAI_API_KEY);
}

export async function buildRemediation(
  category: string,
  title: string,
  evidence: string
): Promise<RemediationOutput> {
  const template = getTemplateForCategory(category);
  if (!template) {
    return {
      template: null as unknown as RemediationTemplate,
      source: "TEMPLATES",
      whyItMatters: "No template matched this category.",
      recommendedFix: "Review manually.",
    };
  }

  if (!isOpenAiConfigured()) {
    return {
      template,
      source: "TEMPLATES",
      whyItMatters: template.whyItMatters,
      recommendedFix: template.recommendedFix,
      note: "Generated from built-in templates. Set OPENAI_API_KEY to enable AI-assisted wording.",
    };
  }

  try {
    const res = await fetch("https://api.openai.com/v1/chat/completions", {
      method: "POST",
      headers: {
        "content-type": "application/json",
        authorization: `Bearer ${process.env.OPENAI_API_KEY}`,
      },
      body: JSON.stringify({
        model: MODEL,
        temperature: 0.2,
        max_tokens: 700,
        messages: [
          {
            role: "system",
            content:
              "You are a senior application security engineer. Explain remediation in plain, specific language for an in-house developer. Do not invent configuration values, headers or versions. Keep it under 150 words total.",
          },
          {
            role: "user",
            content: `Finding: ${title}\nCategory: ${category}\nEvidence: ${evidence}\n\nGive me two short sections:\nWHY: why this matters for this specific observation\nFIX: the recommended fix for their own codebase\nFormat as "WHY: ...\\nFIX: ..."`,
          },
        ],
      }),
      signal: AbortSignal.timeout(20_000),
    });

    if (!res.ok) throw new Error(`OpenAI responded ${res.status}`);

    const json = (await res.json()) as {
      choices?: { message?: { content?: string } }[];
    };
    const content = json.choices?.[0]?.message?.content ?? "";
    const why = /WHY:\s*([\s\S]*?)(?:\nFIX:|$)/i.exec(content)?.[1]?.trim();
    const fix = /FIX:\s*([\s\S]*)$/i.exec(content)?.[1]?.trim();

    if (!why || !fix) throw new Error("Unparseable model response");

    return {
      template,
      source: "AI_ASSISTED",
      whyItMatters: why,
      recommendedFix: fix,
      note: "Wording generated by OpenAI. Code snippets are still taken from the built-in templates.",
    };
  } catch (err) {
    return {
      template,
      source: "TEMPLATES",
      whyItMatters: template.whyItMatters,
      recommendedFix: template.recommendedFix,
      note: `AI assist unavailable (${(err as Error).message}). Fell back to templates.`,
    };
  }
}
